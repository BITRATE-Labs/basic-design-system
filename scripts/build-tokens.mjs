// Builds dist/ from the DTCG sources with Style Dictionary.
//
//   tokens/scales.tokens.json  shared scales (spacing, text, shadow, duration)
//   tokens/roles.tokens.json   shared role names; each aliases {brand.*}
//   brands/<name>.tokens.json  one file per brand; every *.tokens.json there is built
//
// Brand file shape (see brands/basic.tokens.json):
//   {
//     "color": { "light": { "<role>": { "$value": "oklch(...)" }, ... },
//                "dark":  { "<role>": { "$value": "oklch(...)" }, ... } },
//     "font":  { "sans": { "$value": [...] }, "display": {...}, "mono": {...} },
//     "radius": { "$type": "dimension", "$value": "0.625rem" }
//   }
// Every role in tokens/roles.tokens.json needs a light and a dark value.
// A missing one is a broken reference and fails the build.
//
// Outputs:
//   dist/tokens.css         scales + default brand on :root / .dark
//   dist/tokens.ts          scales and role names as TS constants
//   dist/theme.css          Tailwind v4 `@theme inline` mapping
//   dist/brands/<name>.css  roles scoped to [data-brand="<name>"]
//   dist/brands/<name>.ts   concrete values for JS theme objects (Mantine, MUI)
//   dist/brands.css         imports every brand CSS file (Storybook)
import { mkdir, readdir, readFile, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import StyleDictionary from "style-dictionary";

const root = path.resolve(import.meta.dirname, "..");
const dist = path.join(root, "dist");
const DEFAULT_BRAND = "basic";
const MODES = ["light", "dark"];
const transforms = ["name/kebab", "fontFamily/css", "shadow/css/shorthand"];

const readJson = async (file) => JSON.parse(await readFile(file, "utf8"));

async function resolve(config) {
  const sd = new StyleDictionary({
    ...config,
    log: { verbosity: "silent", warnings: "disabled" },
    platforms: { css: { transforms } },
  });
  const { allTokens } = await sd.getPlatformTokens("css");
  return allTokens;
}

// CSS variable name for a token path, following Tailwind v4 / shadcn naming.
function varName(tokenPath) {
  const [head, ...rest] = tokenPath;
  if (head === "color") return `--${rest.join("-")}`;
  if (head === "text") {
    const [size, prop] = rest;
    return prop === "line-height" ? `--text-${size}--line-height` : `--text-${size}`;
  }
  return `--${tokenPath.join("-")}`;
}

const camel = (s) => s.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());
const block = (selector, tokens) =>
  `${selector} {\n${tokens.map((t) => `  ${varName(t.path)}: ${t.$value};`).join("\n")}\n}\n`;
const header = "/* Generated by scripts/build-tokens.mjs. Do not edit. */\n";

async function buildBrand(name) {
  const file = await readJson(path.join(root, "brands", `${name}.tokens.json`));
  const modes = {};
  for (const mode of MODES) {
    if (!file.color?.[mode]) throw new Error(`brands/${name}: missing color.${mode}`);
    const all = await resolve({
      source: [path.join(root, "tokens/roles.tokens.json")],
      tokens: {
        brand: {
          color: { $type: "color", ...file.color[mode] },
          font: file.font,
          radius: file.radius,
        },
      },
    });
    const roles = all.filter((t) => t.path[0] !== "brand");
    modes[mode] = {
      colors: roles.filter((t) => t.path[0] === "color"),
      shared: roles.filter((t) => t.path[0] !== "color"),
    };
  }
  return { name, ...modes };
}

function brandTs({ name, light, dark }) {
  const colors = (tokens) =>
    Object.fromEntries(tokens.map((t) => [camel(t.path.slice(1).join("-")), t.$value]));
  const shared = Object.fromEntries(light.shared.map((t) => [camel(t.path.join("-")), t.$value]));
  const value = {
    name,
    light: colors(light.colors),
    dark: colors(dark.colors),
    font: { sans: shared.fontSans, display: shared.fontDisplay, mono: shared.fontMono },
    radius: shared.radius,
  };
  return `// Generated by scripts/build-tokens.mjs. Do not edit.\nconst brand = ${JSON.stringify(value, null, 2)} as const;\n\nexport default brand;\n`;
}

const themeLines = (roleNames) => [
  ...roleNames.map((r) => `  --color-${r}: var(--${r});`),
  "  --font-sans: var(--font-sans);",
  "  --font-display: var(--font-display);",
  "  --font-mono: var(--font-mono);",
  "  --radius-sm: calc(var(--radius) * 0.6);",
  "  --radius-md: calc(var(--radius) * 0.8);",
  "  --radius-lg: var(--radius);",
  "  --radius-xl: calc(var(--radius) * 1.4);",
  "  --radius-2xl: calc(var(--radius) * 1.8);",
  "  --radius-3xl: calc(var(--radius) * 2.2);",
  "  --radius-4xl: calc(var(--radius) * 2.6);",
];

async function main() {
  await rm(dist, { recursive: true, force: true });
  await mkdir(path.join(dist, "brands"), { recursive: true });

  const brandNames = (await readdir(path.join(root, "brands")))
    .filter((f) => f.endsWith(".tokens.json"))
    .map((f) => f.slice(0, -".tokens.json".length))
    .sort();
  if (!brandNames.includes(DEFAULT_BRAND))
    throw new Error(`missing brands/${DEFAULT_BRAND}.tokens.json`);

  const scales = await resolve({ source: [path.join(root, "tokens/scales.tokens.json")] });
  const brands = await Promise.all(brandNames.map(buildBrand));

  for (const b of brands) {
    const sel = `[data-brand="${b.name}"]`;
    await writeFile(
      path.join(dist, "brands", `${b.name}.css`),
      header +
        block(sel, [...b.light.colors, ...b.light.shared]) +
        block(`${sel}.dark,\n.dark ${sel}`, b.dark.colors),
    );
    await writeFile(path.join(dist, "brands", `${b.name}.ts`), brandTs(b));
  }
  await writeFile(
    path.join(dist, "brands.css"),
    header + brandNames.map((n) => `@import "./brands/${n}.css";`).join("\n") + "\n",
  );

  const def = brands.find((b) => b.name === DEFAULT_BRAND);
  await writeFile(
    path.join(dist, "tokens.css"),
    header +
      block(":root", [...scales, ...def.light.colors, ...def.light.shared]) +
      block(".dark", def.dark.colors),
  );

  const roleNames = def.light.colors.map((t) => t.path.slice(1).join("-"));
  const scaleValues = Object.fromEntries(scales.map((t) => [varName(t.path), t.$value]));
  await writeFile(
    path.join(dist, "tokens.ts"),
    "// Generated by scripts/build-tokens.mjs. Do not edit.\n" +
      `export const colorRoles = ${JSON.stringify(roleNames, null, 2)} as const;\n\n` +
      `export const brands = ${JSON.stringify(brandNames)} as const;\n\n` +
      `export const scales = ${JSON.stringify(scaleValues, null, 2)} as const;\n`,
  );

  const scaleTheme = scales
    .filter((t) => t.path[0] !== "duration") // Tailwind v4 has no duration namespace
    .map((t) => `  ${varName(t.path)}: var(${varName(t.path)});`);
  await writeFile(
    path.join(dist, "theme.css"),
    header +
      "@custom-variant dark (&:is(.dark *));\n\n" +
      `@theme inline {\n${[...themeLines(roleNames), ...scaleTheme].join("\n")}\n}\n`,
  );

  console.log(`tokens: built ${brandNames.length} brand(s): ${brandNames.join(", ")}`);
}

await main();
